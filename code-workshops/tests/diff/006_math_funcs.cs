using System;

class Program
{
    static void Main()
    {
        Console.WriteLine(Math.Abs(-5));
        Console.WriteLine(Math.Abs(-5.5));
        Console.WriteLine(Math.Max(3, 7));
        Console.WriteLine(Math.Max(3, 7.5));
        Console.WriteLine(Math.Min(-3, 7));
        Console.WriteLine(Math.Min(2.5, 1));
        Console.WriteLine(Math.Sqrt(16));
        Console.WriteLine(Math.Sqrt(2));
        Console.WriteLine(Math.Pow(2, 10));
        Console.WriteLine(Math.Pow(2, 0.5));
        Console.WriteLine(Math.Round(3.456));
        Console.WriteLine(Math.Round(3.456, 2));
        Console.WriteLine(Math.PI);
        Console.WriteLine(Math.Floor(-2.5));
        Console.WriteLine(Math.Ceiling(2.1));
        Console.WriteLine(Math.Truncate(-2.7));
        Console.WriteLine(Math.Sqrt(-4));
    }
}
